
import tkinter as tk
from tkinter import messagebox
from datetime import datetime

def create_pdf():
    try:
        aqi = float(aqi_entry.get())
        water = float(water_entry.get())
        waste = waste_entry.get()

        if not 0 <= aqi <= 500:
            raise ValueError

        if not 0 <= water <= 100:
            raise ValueError

        if not waste.strip():
            raise ValueError

        if aqi <= 50:
            risk = "Good"
        elif aqi <= 100:
            risk = "Moderate"
        elif aqi <= 200:
            risk = "Poor"
        elif aqi <= 300:
            risk = "Very Poor"
        else:
            risk = "Severe"

        lines = [
            "ECOGUARD AI",
            "ENVIRONMENTAL MONITORING REPORT",
            "--------------------------------",
            "Date: " + datetime.now().strftime("%d-%m-%Y %H:%M"),
            "Air Quality Index: " + str(aqi),
            "Air Quality Category: " + risk,
            "Water Quality Score: " + str(water) + "%",
            "Waste Management Status: " + waste,
            "--------------------------------",
            "Generated by EcoGuard AI",
            "This report uses user-entered data.",
            "It is not a certified environmental assessment."
        ]

        def clean(text):
            return text.replace("\\", "\\\\").replace(
                "(", "\\("
            ).replace(")", "\\)")

        commands = ["BT", "/F1 16 Tf", "50 790 Td"]
        for i, line in enumerate(lines):
            if i > 0:
                commands.append("0 -35 Td")
            size = 16 if i == 0 else 11
            commands.append("/F1 " + str(size) + " Tf")
            commands.append("(" + clean(line) + ") Tj")

        commands.append("ET")
        stream = "\n".join(commands).encode("ascii")

        objects = [
            b"<< /Type /Catalog /Pages 2 0 R >>",
            b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
            b"<< /Length " + str(len(stream)).encode() +
            b" >>\nstream\n" + stream + b"\nendstream"
        ]

        pdf = b"%PDF-1.4\n"
        offsets = [0]

        for i, obj in enumerate(objects, 1):
            offsets.append(len(pdf))
            pdf += str(i).encode() + b" 0 obj\n"
            pdf += obj + b"\nendobj\n"

        xref = len(pdf)
        pdf += b"xref\n0 6\n"
        pdf += b"0000000000 65535 f \n"

        for offset in offsets[1:]:
            pdf += ("%010d 00000 n \n" % offset).encode()

        pdf += b"trailer\n<< /Size 6 /Root 1 0 R >>\n"
        pdf += b"startxref\n" + str(xref).encode() + b"\n%%EOF"

        with open("EcoGuard_Report.pdf", "wb") as file:
            file.write(pdf)

        messagebox.showinfo(
            "Success",
            "PDF Report Created Successfully!\nEcoGuard_Report.pdf"
        )

    except ValueError:
        messagebox.showerror(
            "Error",
            "Enter valid AQI, water score and waste status."
        )

root = tk.Tk()
root.title("EcoGuard AI - PDF Report Generator")
root.geometry("550x550")
root.configure(bg="#10251d")

tk.Label(
    root, text="ENVIRONMENTAL REPORT GENERATOR",
    font=("Arial", 17, "bold"),
    bg="#10251d", fg="white"
).pack(pady=25)

def add_field(label):
    tk.Label(
        root, text=label,
        bg="#10251d", fg="white",
        font=("Arial", 12)
    ).pack(pady=5)

    entry = tk.Entry(root, font=("Arial", 13), width=25)
    entry.pack(pady=5)
    return entry

add_field("Air Quality Index (0-500)")
aqi_entry = tk.Entry(root, font=("Arial", 13), width=25)
aqi_entry.pack()

add_field("Water Quality Score (0-100)")
water_entry = tk.Entry(root, font=("Arial", 13), width=25)
water_entry.pack()

add_field("Waste Status (e.g. Managed)")
waste_entry = tk.Entry(root, font=("Arial", 13), width=25)
waste_entry.pack()

tk.Button(
    root, text="GENERATE PDF REPORT",
    command=create_pdf,
    bg="#35a66a", fg="white",
    font=("Arial", 12, "bold"),
    padx=20, pady=12
).pack(pady=30)

root.mainloop()
